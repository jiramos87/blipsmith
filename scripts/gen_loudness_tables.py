#!/usr/bin/env python3
"""Write core/src/loudness_tables.h: the baked constants the loudness measures use.

The core may not call a libm transcendental, and the K-weighting filters of
ITU-R BS.1770 are defined through `tan` and `pow`. So they are worked out here,
once, offline, for each sample rate the spec allows, and committed as literals.
The same goes for the true-peak interpolator, a windowed sinc that needs `sin`
and `cos`. Re-run after changing a formula, never by hand:

    uv run python scripts/gen_loudness_tables.py > core/src/loudness_tables.h

The filter formulas are the ones libebur128 uses, which reproduce the published
48 kHz coefficients of BS.1770-4 and carry them to any other rate.
"""

from __future__ import annotations

import math
import sys

from blipsmith.ranges import SUPPORTED_SAMPLE_RATES

SHELF_HZ = 1681.974450955533
SHELF_GAIN_DB = 3.999843853973347
SHELF_Q = 0.7071752369554196
HIGHPASS_HZ = 38.13547087602444
HIGHPASS_Q = 0.5003270373238773

OVERSAMPLE = 4
TAPS_PER_PHASE = 12  # x[k-5] .. x[k+6]
FIRST_TAP = -5


def shelf(rate: int) -> list[float]:
    k = math.tan(math.pi * SHELF_HZ / rate)
    vh = 10.0 ** (SHELF_GAIN_DB / 20.0)
    vb = vh**0.4996667741545416
    a0 = 1.0 + k / SHELF_Q + k * k
    return [
        (vh + vb * k / SHELF_Q + k * k) / a0,
        2.0 * (k * k - vh) / a0,
        (vh - vb * k / SHELF_Q + k * k) / a0,
        2.0 * (k * k - 1.0) / a0,
        (1.0 - k / SHELF_Q + k * k) / a0,
    ]


def highpass(rate: int) -> list[float]:
    k = math.tan(math.pi * HIGHPASS_HZ / rate)
    a0 = 1.0 + k / HIGHPASS_Q + k * k
    return [1.0, -2.0, 1.0, 2.0 * (k * k - 1.0) / a0, (1.0 - k / HIGHPASS_Q + k * k) / a0]


def interpolator() -> list[list[float]]:
    """Phases 1..3 of a 4x Hann-windowed sinc; phase 0 is the sample itself."""
    half = TAPS_PER_PHASE / 2
    phases = []
    for phase in range(1, OVERSAMPLE):
        offset = phase / OVERSAMPLE
        taps = []
        for index in range(TAPS_PER_PHASE):
            t = offset - (FIRST_TAP + index)
            sinc = math.sin(math.pi * t) / (math.pi * t)
            window = 0.5 * (1.0 + math.cos(math.pi * t / half))
            taps.append(sinc * window)
        phases.append(taps)
    return phases


def literal(value: float) -> str:
    return repr(float(value))


def main() -> int:
    out = sys.stdout
    out.write("// Generated by scripts/gen_loudness_tables.py. Do not edit by hand.\n")
    out.write("//\n// K-weighting biquads per sample rate as {b0, b1, b2, a1, a2}, and the\n")
    out.write("// phases 1 to 3 of the 4x true-peak interpolator (taps x[k-5] .. x[k+6]).\n\n")
    out.write("#pragma once\n\nnamespace blipsmith {\n\n")
    out.write("struct KWeighting {\n    int sampleRate;\n    double shelf[5];\n")
    out.write("    double highpass[5];\n};\n\n")
    out.write(f"inline constexpr int kKWeightingRates = {len(SUPPORTED_SAMPLE_RATES)};\n")
    out.write("inline constexpr KWeighting kKWeighting[kKWeightingRates] = {\n")
    for rate in SUPPORTED_SAMPLE_RATES:
        s = ", ".join(literal(v) for v in shelf(rate))
        h = ", ".join(literal(v) for v in highpass(rate))
        out.write(f"    {{{rate}, {{{s}}}, {{{h}}}}},\n")
    out.write("};\n\n")
    out.write(f"inline constexpr int kTruePeakTaps = {TAPS_PER_PHASE};\n")
    out.write(f"inline constexpr int kTruePeakFirstTap = {FIRST_TAP};\n")
    out.write(f"inline constexpr int kTruePeakPhases = {OVERSAMPLE - 1};\n")
    out.write("inline constexpr double kTruePeakInterpolator[kTruePeakPhases][kTruePeakTaps] = {\n")
    for taps in interpolator():
        out.write("    {" + ", ".join(literal(v) for v in taps) + "},\n")
    out.write("};\n\n}  // namespace blipsmith\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
